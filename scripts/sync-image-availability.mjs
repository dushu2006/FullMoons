#!/usr/bin/env node
/**
 * Syncs runtime-safe image paths.
 *
 * src/config/menu-images.ts is the *intended* manifest: it maps every
 * dish to its dedicated photograph. Photographs are generated in
 * batches, so some intended files may not exist on disk yet. This
 * script writes src/config/menu-image-availability.ts, which resolves
 * every reference to a file that actually exists:
 *
 *   intended photo  →  exists? use it
 *                    →  missing? use the category's representative
 *                       photo, else the diet overview photo, else the
 *                       neutral fallback photo
 *
 * The result: the website never shows a broken image, and the
 * dedicated photograph lights up automatically once it is generated
 * and the script is re-run. Run after every generation batch:
 *
 *   node scripts/sync-image-availability.mjs
 */

import fs from "node:fs";
import path from "node:path";
import ts from "typescript";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const manifestTs = fs.readFileSync(path.join(root, "src/config/menu-images.ts"), "utf8");
const { outputText } = ts.transpileModule(manifestTs, {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
});
const tmp = path.join(root, ".cache", "menu-images-intended.cjs");
fs.mkdirSync(path.dirname(tmp), { recursive: true });
fs.writeFileSync(tmp, outputText);

const intended = await import(tmp);
const {
  menuImageMap,
  categoryImageMap,
  galleryImages,
  heroImage,
  introImage,
  dietOverviewImages,
  dishImagePairs,
} = intended;

const exists = (src) => fs.existsSync(path.join(root, "public", src));

// Dish name → category and diet (for representative/diet fallback)
const siteTs = fs.readFileSync(path.join(root, "src/config/site.ts"), "utf8");
const menuBlock = siteTs.slice(siteTs.indexOf("menuOverview:"), siteTs.indexOf("  ],\n\n} as const;"));
const dishCategory = new Map();
const dishDiet = new Map();
const categoryRe = /category: "([^"]+)"[\s\S]*?items: \[([\s\S]*?)\],\s*\},/g;
let match;
while ((match = categoryRe.exec(menuBlock)) !== null) {
  const itemRe = /\{ name: "((?:[^"\\]|\\.)*)", price: (\d+), description: "((?:[^"\\]|\\.)*)", diet: "([^"]+)" \}/g;
  let itemMatch;
  while ((itemMatch = itemRe.exec(match[2])) !== null) {
    dishCategory.set(itemMatch[1].replace(/\\"/g, '"'), match[1]);
    dishDiet.set(itemMatch[1].replace(/\\"/g, '"'), itemMatch[4]);
  }
}

const FALLBACK = intended.FALLBACK_MENU_IMAGE;
const DIET_FALLBACK = { veg: FALLBACK, "non-veg": "/images/featured-starters.jpg", egg: "/images/featured-starters.jpg" };
const pending = [];

function resolvePath(src, category, diet) {
  if (exists(src)) return src;
  pending.push(src);
  const rep = categoryImageMap[category];
  if (rep && rep !== src && exists(rep)) return rep;
  const dietImg = diet && dietOverviewImages[diet];
  if (dietImg && exists(dietImg)) return dietImg;
  return DIET_FALLBACK[diet] ?? FALLBACK;
}

const lines = [];
lines.push("/**");
lines.push(" * GENERATED by scripts/sync-image-availability.mjs — do not edit.");
lines.push(" * Runtime-safe image paths derived from the intended manifest in");
lines.push(" * src/config/menu-images.ts. Any reference whose dedicated");
lines.push(" * photograph has not been generated yet resolves to the closest");
lines.push(" * existing photograph (category representative → diet overview →");
lines.push(" * neutral fallback), so the site never shows a broken image.");
lines.push(" */");
lines.push("");
lines.push("");
lines.push(`export const availableMenuImageMap: Record<string, string> = ${JSON.stringify(
  Object.fromEntries(
    Object.entries(menuImageMap).map(([name, src]) => [
      name,
      resolvePath(src, dishCategory.get(name), dishDiet.get(name)),
    ]),
  ),
  null,
  2,
)};`);
lines.push("");
lines.push(`export const availableCategoryImageMap: Record<string, string> = ${JSON.stringify(
  Object.fromEntries(
    Object.entries(categoryImageMap).map(([cat, src]) => [cat, resolvePath(src, cat, undefined)]),
  ),
  null,
  2,
)};`);
lines.push("");
lines.push(`export const dietOverviewImages = ${JSON.stringify(
  Object.fromEntries(
    Object.entries(dietOverviewImages).map(([diet, src]) => [diet, resolvePath(src, null, diet)]),
  ),
  null,
  2,
)} as const;`);
lines.push("");
// Gallery only shows photographs that actually exist — never
// repeats a fallback tile — so it stays varied while batches
// are still being generated.
const safeGallery = galleryImages.filter((g) => exists(g.src));
lines.push(`export const availableGalleryImages = ${JSON.stringify(safeGallery, null, 2)} as const;`);
lines.push("");
lines.push(`export const availableHeroImage = ${JSON.stringify(
  { ...heroImage, src: resolvePath(heroImage.src, null, null) },
  null,
  2,
)};`);
lines.push("");
lines.push(`export const availableIntroImage = ${JSON.stringify(
  { ...introImage, src: resolvePath(introImage.src, null, null) },
  null,
  2,
)};`);
lines.push("");
lines.push(`/** Photographs still awaiting generation (intended manifest). */`);
lines.push(`export const pendingImagePaths = ${JSON.stringify([...new Set(pending)].sort(), null, 2)};`);
lines.push("");
lines.push(`import { FALLBACK_MENU_IMAGE, menuImageMap as intendedMenuImageMap, getMenuImageAlt as intendedAlt } from "./menu-images";`);
lines.push("");
lines.push("/** Dedicated photograph when it exists; closest honest existing photo otherwise. */");
lines.push("export function getMenuImage(dishName: string): string {");
lines.push("  return availableMenuImageMap[dishName] ?? FALLBACK_MENU_IMAGE;");
lines.push("}");
lines.push("");
lines.push("/** Alt text describes the photograph actually displayed. */");
lines.push("export function getMenuImageAlt(dishName: string): string {");
lines.push("  const src = availableMenuImageMap[dishName];");
lines.push("  if (src && src === intendedMenuImageMap[dishName]) return intendedAlt(dishName);");
lines.push("  return `${dishName} from the FULL MOONs Family Restaurant menu`;");
lines.push("}");
lines.push("");
lines.push("/** Representative category thumbnail, safe against missing files. */");
lines.push("export function getCategoryImage(category: string): string {");
lines.push("  return availableCategoryImageMap[category] ?? FALLBACK_MENU_IMAGE;");
lines.push("}");
lines.push("");

fs.writeFileSync(path.join(root, "src/config/menu-image-availability.ts"), lines.join("\n"));

const total = Object.keys(menuImageMap).length + Object.keys(categoryImageMap).length + galleryImages.length + 3;
console.log(`Resolved ${total} references; ${new Set(pending).size} photographs still pending generation.`);
console.log(`Gallery tiles live: ${safeGallery.length}/${galleryImages.length}.`);
